#!/usr/bin/env node
// 技能大典 · 技能仓库总目生成器（零依赖）
// 用法: node scripts/build-skill-repos.mjs --lang=en|zh
// 读 data/skill-repos.jsonl（及可选 skill-repos.partN.jsonl 分片）+ meta，写 INDEX/skill-repos.md。
// 请改 jsonl / meta，勿手改生成文件。

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSkillRepos } from './load-skill-repos.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const langArg = process.argv.find(a => a.startsWith('--lang='));
const LANG = (langArg ? langArg.slice('--lang='.length) : process.env.SKILL_LANG || '').toLowerCase();
if (!['en', 'zh'].includes(LANG)) {
  console.error('用法：node scripts/build-skill-repos.mjs --lang=en|zh（也可设置 SKILL_LANG）');
  process.exit(2);
}
const STATUS_EN = { '仅索引': 'indexed-only', '已采编': 'curated', '本项目': 'this-project' };
function pickSummary(o) {
  if (LANG === 'zh') {
    const zh = o.summary_zh;
    if (zh != null && String(zh).trim()) return zh;
  }
  return o.summary;
}
function pickStatus(s) {
  const v = String(s ?? '');
  if (LANG !== 'en') return v;
  return STATUS_EN[v] || v;
}
const META = path.join(ROOT, 'data', 'skill-repos.meta.md');
const OUT = path.join(ROOT, 'INDEX', 'skill-repos.md');

const SECTIONS_ZH = [
  { id: 'official', heading: '## 1. 官方与权威' },
  { id: 'collections', heading: '## 2. 精选列表 / 大集合' },
  { id: 'vertical', heading: '## 3. 垂直领域技能包' },
  { id: 'infra', heading: '## 4. 安装器 / 注册表 / 基础设施' },
  { id: 'other', heading: '## 5. 其他值得索引的技能库' },
  {
    id: 'unnamed',
    heading: '## 6. 名称不含 skill / agent 的技能库（本轮追加）',
    lead: '仓库名往往是方法论、产品或梗。判定依据是 README：可安装的 SKILL.md / Claude 插件市场 / `npx skills add`。',
  },
];
const SECTIONS_EN = [
  { id: 'official', heading: '## 1. Official' },
  { id: 'collections', heading: '## 2. Collections' },
  { id: 'vertical', heading: '## 3. Vertical' },
  { id: 'infra', heading: '## 4. Infra' },
  { id: 'other', heading: '## 5. Other' },
  {
    id: 'unnamed',
    heading: '## 6. Unnamed (repo name lacks skill / agent)',
    lead: 'Names are often methodologies, products, or memes. Inclusion is based on README: installable SKILL.md / Claude plugin marketplace / `npx skills add`.',
  },
];
const SECTIONS = LANG === 'en' ? SECTIONS_EN : SECTIONS_ZH;
let repos;
try {
  repos = await loadSkillRepos();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}

function fmtStars(n) {
  return Math.trunc(n).toLocaleString('en-US');
}

function cell(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

const COLS = LANG === 'en'
  ? '| Repo | Stars | README summary | License | Skills | Status |'
  : '| 仓库 | Stars | README 摘要 | 许可 | 技能数 | 采编 |';
const SEP = '|---|---:|---|---|---|---|';

function table(list) {
  const rows = list.map(r =>
    `| [${cell(r.full_name)}](${r.html_url}) | ${fmtStars(r.stars)} | ${cell(pickSummary(r))} | ${cell(r.license)} | ${cell(r.skill_count)} | ${cell(pickStatus(r.status))} |`
  );
  return [COLS, SEP, ...rows].join('\n');
}

let meta = await fs.readFile(META, 'utf8');
meta = meta.replaceAll('{{COUNT}}', String(repos.length));
meta = meta.replace(/^# 技能仓库总目\s*\n+/ , '');

const chunks = [];
chunks.push(LANG === 'en' ? '# Skill repos index' : '# 技能仓库总目');
chunks.push('');
chunks.push(LANG === 'en'
  ? '> Generated by scripts/build-skill-repos.mjs — edit data/skill-repos.jsonl, do not hand-edit this file.'
  : '> 由 scripts/build-skill-repos.mjs 生成，请改 data/skill-repos.jsonl，勿手改本文件。');
chunks.push('');
chunks.push(meta.trimEnd());
chunks.push('');

for (const sec of SECTIONS) {
  const list = repos.filter(r => r.section === sec.id);
  if (!list.length) continue;
  chunks.push(sec.heading);
  chunks.push('');
  if (sec.lead) {
    chunks.push(sec.lead);
    chunks.push('');
  }
  chunks.push(table(list));
  chunks.push('');
}

await fs.mkdir(path.dirname(OUT), { recursive: true });
await fs.writeFile(OUT, chunks.join('\n').replace(/\n+$/, '\n'));
console.log((LANG === 'en' ? 'Wrote INDEX/skill-repos.md: ' : '已生成 INDEX/skill-repos.md：') + repos.length + (LANG === 'en' ? ' repos' : ' 个独立仓库。'));
